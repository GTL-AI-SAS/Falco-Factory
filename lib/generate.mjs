import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const BASE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATE = path.join(BASE, 'templates/worker');
const OWNED = ['package.json', 'wrangler.json', '.gitignore', 'README.md', 'src/index.mjs', 'src/business-context.mjs', 'src/providers/index.mjs', 'src/providers/mock.mjs', 'src/providers/openai.mjs', 'src/providers/gemini.mjs', 'src/providers/shared.mjs', '.falco-generated.json'];
function pretty(x) { return JSON.stringify(x, null, 2) + '\n'; }
export function buildConfig(c) {
  return { $schema: 'node_modules/wrangler/config-schema.json', name: c.name, main: 'src/index.mjs',
    compatibility_date: '2026-11-01', workers_dev: true, preview_urls: false,
    ...(c.accountId ? { account_id: c.accountId } : {}),
    observability: { enabled: false },
    vars: { BUSINESS_NAME: c.business, PROVIDER: c.provider, MODEL: c.model, ALLOWED_ORIGIN: c.origin, ALLOWED_ORIGINS: JSON.stringify(c.origins ?? [c.origin]),
      MOCK_REPLY: c.mockReply },
    ratelimits: [{ name: 'CHAT_RATE_LIMITER', namespace_id: c.namespaceId, simple: { limit: c.rateLimit, period: 60 } }] };
}
export async function generate(c) {
  const exists = await fs.stat(c.output).then(() => true, e => { if (e.code === 'ENOENT') return false; throw e; });
  if (exists && !c.force) throw new Error(`Project directory exists: ${c.output}. Choose --output or use --force (generated projects only).`);
  if (exists) {
    const marker = await fs.readFile(path.join(c.output, '.falco-generated.json'), 'utf8').catch(() => null);
    let m;
    try { m = JSON.parse(marker); } catch { throw new Error(`Refusing to overwrite non-Falco directory: ${c.output}`); }
    if (!m || m.generator !== 'falco-factory') throw new Error(`Refusing to overwrite non-Falco directory: ${c.output}`);
    if (m.worker !== c.name) throw new Error('Refusing to overwrite directory belonging to a different Worker');
  }
  if (c.dryRun) return { files: OWNED, exists, written: false };
  await fs.mkdir(path.join(c.output, 'src/providers'), { recursive: true });
  for (const p of ['src/index.mjs','src/providers/index.mjs','src/providers/mock.mjs','src/providers/openai.mjs','src/providers/gemini.mjs','src/providers/shared.mjs']) {
    await fs.copyFile(path.join(TEMPLATE, p), path.join(c.output, p));
  }
  const pkg = { name: c.name, private: true, version: '0.8.0', type: 'module',
    scripts: { dev: 'wrangler dev', deploy: 'wrangler deploy', 'secret:openai': 'wrangler secret put OPENAI_API_KEY',
      'secret:gemini': 'wrangler secret put GEMINI_API_KEY' }, devDependencies: { wrangler: '^4.0.0' } };
  await fs.writeFile(path.join(c.output, 'src/business-context.mjs'),
    `// Public, non-secret business text bundled by Falco Factory.\nexport const businessInstructions = ${JSON.stringify(c.instructions)};\nexport const faqText = ${JSON.stringify(c.faq)};\n`);
  await fs.writeFile(path.join(c.output,'package.json'), pretty(pkg));
  await fs.writeFile(path.join(c.output,'wrangler.json'), pretty(buildConfig(c)));
  await fs.writeFile(path.join(c.output,'.gitignore'), 'node_modules/\n.wrangler/\n.dev.vars*\n.env*\n*.log\n');
  await fs.writeFile(path.join(c.output,'.falco-generated.json'), pretty({ generator: 'falco-factory', version: '0.8.0', worker: c.name, managedFiles: OWNED }));
  await fs.writeFile(path.join(c.output,'README.md'), `# ${c.name}\n\nGenerated by GTL AI Falco Factory v0.8.\n\nBusiness: ${c.business}\nProvider: ${c.provider}\nAllowed origins (CORS):\n${(c.origins ?? [c.origin]).map(x => '- ' + x).join('\n')}\n\nInstall: \`npm install\`\nLocal dev: \`npm run dev\`\nDeploy: \`npm run deploy\`\n\nProvider credentials are Cloudflare secrets (not wrangler vars). Set using \`npm run secret:${c.provider === 'gemini' ? 'gemini' : 'openai'}\` when using a real provider.\n\n**Warning:** this is a public endpoint with approximate per-IP, per-PoP Cloudflare rate limiting. CORS is not authentication. Add WAF rules, quotas, and a custom domain before paid production traffic.\n`);
  return { files: OWNED, exists, written: true };
}
